export function findWoundVocabularySeedBySeed(
  seedId: string,
): WoundSeed | undefined {
  const normalizedSeedId = seedId.trim().toLowerCase();
  return WOUND_VOCABULARY_SEEDS.find(
    (seed) => seed.seed.toLowerCase() === normalizedSeedId,
  );
}

export function getWoundVocabularySeedsByCategory(
  category: string,
): readonly WoundSeed[] {
  const normalizedCategory = category.trim().toLowerCase();
  return WOUND_VOCABULARY_SEEDS.filter(
    (seed) => seed.metadata.category.toLowerCase() === normalizedCategory,
  );
}
