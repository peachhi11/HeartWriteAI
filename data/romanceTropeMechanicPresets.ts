function createRomanceTropeMechanicPreset(
  group: MechanicSeedGroup,
  value: string,
): RomanceTropeMechanicPreset {
  const label = toTitleLabel(value);
  return {
    id: `${group.prefix}_${slugify(value)}`,
    mechanic: group.mechanic,
    category: group.category,
    label,
    value,
    triggerKeys: buildTriggerKeys(value, group),
    guidance: group.guidance,
    systemPromptTags: [
      `${group.mechanic.toLowerCase()} trope mechanic`,
      `${group.category.toLowerCase()} cue`,
      `${slugify(value).replace(/_/g, " ")} cue`,
    ],
  };
}

function buildTriggerKeys(value: string, group: MechanicSeedGroup): string[] {
  return uniquePreserveOrder([
    ...value
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/["'.,]/g, "")
      .split(/\s+|-/)
      .filter((part) => part.length > 2),
    group.mechanic.toLowerCase(),
    group.category.toLowerCase(),
    "romance",
    "trope",
    "mechanic",
  ]);
}

function slugify(value: string): string {
  return value
    .trim()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/'s\b/g, "s")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function toTitleLabel(value: string): string {
  if (/^The\s/.test(value)) return value;
  if (/[.!?]$/.test(value)) return value;
  return value
    .split(/\s+/)
    .map((word) => (word ? word[0]?.toUpperCase() + word.slice(1) : word))
    .join(" ");
}

function uniquePreserveOrder(values: string[]): string[] {
  return values.filter((value, index, array) => array.indexOf(value) === index);
}
