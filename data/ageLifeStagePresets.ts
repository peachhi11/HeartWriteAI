function createAgeLifeStagePreset(
  group: AgeLifeStageSeedGroup,
  value: string,
): AgeLifeStagePreset {
  const readableValue = normaliseReadableAgeLifeStageValue(value);
  const label = toTitleLabel(readableValue);
  const triggerKeys = uniquePreserveOrder([
    ...value
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/["'.,]/g, "")
      .split(/\s+|-/)
      .filter((part) => part.length > 2),
    group.category.toLowerCase(),
    "age",
    "adult",
    "life stage",
    "maturity",
  ]);

  return {
    id: `${group.prefix}_${slugify(value)}`,
    category: group.category,
    label,
    value: readableValue,
    triggerKeys,
    guidance: normaliseReadableAgeLifeStageValue(group.guidance),
    systemPromptTags: [
      `${group.category.toLowerCase()} age life stage texture`,
      `${slugify(value).replace(/_/g, " ")} cue`,
    ],
  };
}

function normaliseReadableAgeLifeStageValue(value: string): string {
  return value
    .replace(/\bvs\b/gi, (match) => match[0] === "V" ? "Versus" : "versus")
    .replace(/\bcenter\b/gi, (match) => match[0] === "C" ? "Centre" : "centre")
    .replace(/\bcenters\b/gi, (match) => match[0] === "C" ? "Centres" : "centres");
}

function slugify(value: string): string {
  return value
    .trim()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/'s\b/g, "s")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function toTitleLabel(value: string): string {
  if (/^The\s/.test(value)) return value;
  if (/[.!?]$/.test(value)) return value;
  return value
    .split(/\s+/)
    .map((word) => (word ? word[0]?.toUpperCase() + word.slice(1) : word))
    .join(" ");
}

function uniquePreserveOrder(values: string[]): string[] {
  return values.filter((value, index, array) => array.indexOf(value) === index);
}
