import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(repoRoot, "skills", "manifest.json");
const outputPath = path.join(repoRoot, "lib", "character-card", "generatedRuntimeSkillMetadata.ts");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const linkedEntries = manifest.entries.filter((entry) => entry.runtime_metadata_path);
const failures = [];
const records = [];

for (const entry of linkedEntries) {
  const metadataPath = path.join(repoRoot, entry.runtime_metadata_path);
  if (!fs.existsSync(metadataPath)) {
    failures.push(`${entry.slug}: missing ${entry.runtime_metadata_path}`);
    continue;
  }

  const metadata = JSON.parse(fs.readFileSync(metadataPath, "utf8"));
  if (metadata.identity?.slug !== entry.slug)
    failures.push(`${entry.slug}: metadata slug does not match manifest`);
  if (metadata.provenance?.repository_body !== entry.repository_path)
    failures.push(`${entry.slug}: metadata body does not match manifest`);
  records.push(metadata);
}

const metadataFiles = fs.existsSync(path.join(repoRoot, "skills", "runtime-metadata"))
  ? fs
      .readdirSync(path.join(repoRoot, "skills", "runtime-metadata"))
      .filter((file) => file.endsWith(".json"))
      .sort()
  : [];
const linkedFiles = new Set(
  linkedEntries.map((entry) => path.basename(entry.runtime_metadata_path)),
);
for (const file of metadataFiles) {
  if (!linkedFiles.has(file))
    failures.push(
      `runtime metadata file is not linked from manifest: skills/runtime-metadata/${file}`,
    );
}

if (failures.length > 0) {
  console.error("Runtime skill metadata generation failed:");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const generatedSource = `/**
 * Generated by scripts/generate-runtime-skill-metadata.mjs.
 * Do not edit this file directly; update skills/runtime-metadata/*.json instead.
 */
export const runtimeSkillMetadataRecords = ${JSON.stringify(records, null, 2)} as const;
`;
const generated = await prettier.format(generatedSource, { parser: "typescript" });

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error(
      `Generated runtime skill metadata is stale: ${path.relative(repoRoot, outputPath)}`,
    );
    process.exit(1);
  }
  console.log(`Generated runtime skill metadata is current for ${records.length} records`);
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`Generated runtime skill metadata for ${records.length} records`);
}
